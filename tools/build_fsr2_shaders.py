"""Compile AMD FSR 2.2's GLSL passes (runtime/third_party/fsr2/shaders, MIT) into runtime/third_party/fsr2/
fsr2_shaders_gen.h: SPIR-V words and each pass's resource names and bindings, in the shape the FSR 2.2 Vulkan
backend reads (vk/shaders/ffx_fsr2_shaders_vk.h Fsr2ShaderBlobVK). It stands in for AMD's FidelityFX_SC compiler,
which this repository does not run: glslc compiles each pass and spirv-cross --reflect names its bindings.

Only the variants the runtime asks for are built (vk_fsr2.cpp sets the context flags): LDR colour, motion vectors at
the render resolution and not jittered, depth not inverted, no 16-bit maths; the two options the backend chooses
itself stay variants: the reprojection's Lanczos LUT and, for the accumulate pass, sharpening. Run after editing a
pass; the header is committed, so the game builds without glslc. Needs glslc and spirv-cross (MSYS2 UCRT64:
shaderc, spirv-cross).

    python tools/build_fsr2_shaders.py
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FSR2 = ROOT / 'runtime' / 'third_party' / 'fsr2'
BIN = Path(r'C:\msys64\ucrt64\bin') if os.name == 'nt' else None
PASSES = ['depth_clip', 'reconstruct_previous_depth', 'lock', 'accumulate', 'rcas', 'compute_luminance_pyramid',
          'autogen_reactive', 'tcr_autogen']
BASE = ['-DFFX_GPU=1', '-DFFX_GLSL=1', '-DFFX_HALF=0',
        '-DFFX_FSR2_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0', '-DFFX_FSR2_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0',
        '-DFFX_FSR2_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=1',
        '-DFFX_FSR2_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0',
        '-DFFX_FSR2_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2', '-DFFX_FSR2_OPTION_HDR_COLOR_INPUT=0',
        '-DFFX_FSR2_OPTION_LOW_RESOLUTION_MOTION_VECTORS=1', '-DFFX_FSR2_OPTION_JITTERED_MOTION_VECTORS=0',
        '-DFFX_FSR2_OPTION_INVERTED_DEPTH=0']


def tool(name):
    return str(BIN / (name + '.exe')) if BIN else name


def compile_pass(name, lanczos, sharpen, tmp):
    src = FSR2 / 'shaders' / f'ffx_fsr2_{name}_pass.glsl'
    out = Path(tmp) / f'{name}_{lanczos}{sharpen}.spv'
    args = [tool('glslc'), '-fshader-stage=compute', '--target-env=vulkan1.1', *BASE,
            f'-DFFX_FSR2_OPTION_REPROJECT_USE_LANCZOS_TYPE={lanczos}', f'-DFFX_FSR2_OPTION_APPLY_SHARPENING={sharpen}',
            '-I', str(FSR2 / 'shaders'), str(src), '-o', str(out)]
    subprocess.run(args, check=True)   # unoptimised: the binding names survive for the reflection
    refl = json.loads(subprocess.run([tool('spirv-cross'), str(out), '--reflect'], check=True, capture_output=True,
                                     text=True).stdout)
    subprocess.run(args[:1] + ['-O'] + args[1:], check=True)   # the blob itself, optimised (same bindings)
    pick = lambda key: sorted((x['name'], x['binding']) for x in refl.get(key, []) if x.get('set', 0) == 1)
    ubos = [(n[:-2] if n.endswith('_t') else n, b) for n, b in pick('ubos')]
    return out.read_bytes(), pick('images'), pick('separate_images'), ubos


def c_names(prefix, items):
    names = ', '.join(f'"{n}"' for n, _ in items) or '0'
    binds = ', '.join(str(b) for _, b in items) or '0'
    return (f'static const char *{prefix}_n[] = {{{names}}};\nstatic const uint32_t {prefix}_b[] = {{{binds}}};\n')


def main():
    lines = ['// Generated by tools/build_fsr2_shaders.py from runtime/third_party/fsr2/shaders (AMD FSR 2.2, MIT);',
             '// do not edit.', '#pragma once', '#include <stdint.h>', '']
    table = []
    seen = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name in PASSES:
            for lanczos in (0, 1):
                for sharpen in ((0, 1) if name == 'accumulate' else (0,)):
                    blob, uav, srv, cb = compile_pass(name, lanczos, sharpen, tmp)
                    v = f'fsr2_{name}_{lanczos}{sharpen}'
                    words = [int.from_bytes(blob[i:i + 4], 'little') for i in range(0, len(blob), 4)]
                    same = seen.get(blob)   # most passes do not use the Lanczos option: one copy of the words
                    if same:
                        lines.append(f'#define {v}_spv {same}_spv')
                    else:
                        seen[blob] = v
                        lines.append(f'static const uint32_t {v}_spv[] = {{')
                        for i in range(0, len(words), 12):
                            lines.append(','.join(f'0x{w:x}' for w in words[i:i + 12]) + ',')
                        lines.append('};')
                    lines.append(c_names(v + '_uav', uav) + c_names(v + '_srv', srv) + c_names(v + '_cb', cb))
                    table.append((name, lanczos, sharpen, v, len(uav), len(srv), len(cb)))
                    print(f'{v}: {len(words)} words, {len(uav)} storage, {len(srv)} sampled, {len(cb)} uniform')
    lines.append('typedef struct { const char *pass; int lanczos, sharpen; const uint32_t *spv; uint32_t size, nuav, nsrv, ncb;')
    lines.append('    const char **uav_n; const uint32_t *uav_b; const char **srv_n; const uint32_t *srv_b; const char **cb_n;')
    lines.append('    const uint32_t *cb_b; } Fsr2GenBlob;')
    lines.append('static const Fsr2GenBlob fsr2_gen_blobs[] = {')
    for name, l, s, v, nu, ns, nc in table:
        lines.append(f'    {{"{name}", {l}, {s}, {v}_spv, sizeof {v}_spv, {nu}, {ns}, {nc}, {v}_uav_n, {v}_uav_b, {v}_srv_n, '
                     f'{v}_srv_b, {v}_cb_n, {v}_cb_b}},')
    lines.append('};')
    (FSR2 / 'fsr2_shaders_gen.h').write_text('\n'.join(lines) + '\n', newline='\n')
    print('wrote', FSR2 / 'fsr2_shaders_gen.h')


if __name__ == '__main__':
    sys.exit(main())
